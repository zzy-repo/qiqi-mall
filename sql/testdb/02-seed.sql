       FLOOR(s.stock / 8) + IF(seq.n = 0, s.stock - FLOOR(s.stock / 8) * 8, 0)
  FROM sku s
  CROSS JOIN (SELECT 0 AS n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3
